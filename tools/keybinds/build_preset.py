"""Build the Forge 1.12.2 launcher preset from the reviewed bindings."""
from dataclasses import dataclass
from itertools import combinations
from pathlib import Path
import re

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent.parent
PRESET = ROOT / "launcher/controls-preset.txt"
CHORD = re.compile(r"(?:0|-10[0]|-9[6-9]|[1-9]\d{0,2})(?::(?:CONTROL|ALT|SHIFT))?")
CONTEXTS = {"game", "inventory", "map", "all", "ae_terminal", "bq_screen", "oc_terminal", "treechop_gui"}
MODIFIER_KEYS = {"SHIFT": {42, 54}, "CONTROL": {29, 157}, "ALT": {56, 184}}
RESERVED = {1, 59, 60, 61, 63, 87}


@dataclass(frozen=True)
class Binding:
    ids: tuple[str, ...]
    default: str
    preset: str
    contexts: frozenset[str]


def load_bindings():
    bindings = []
    seen = set()
    for number, line in enumerate((TOOLS / "bindings.tsv").read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        names, default, preset, context = line.split("\t")
        ids = tuple(names.split("|"))
        contexts = frozenset(context.split(","))
        if len(set(ids)) != len(ids) or any(not name or name != name.strip() or ":" in name
                                          or name in seen for name in ids):
            raise ValueError(f"Invalid or repeated ID on row {number}")
        if not contexts <= CONTEXTS or any(not CHORD.fullmatch(chord) for chord in (default, preset)):
            raise ValueError(f"Invalid chord or context on row {number}")
        code, _, modifier = preset.partition(":")
        if (preset.startswith("0:") or int(code) > 255
                or int(code) in MODIFIER_KEYS.get(modifier, ())):
            raise ValueError(f"Invalid LWJGL code on row {number}")
        seen.update(ids)
        bindings.append(Binding(ids, default, preset, contexts))
    return bindings


def overlaps(left, right):
    if "all" in left | right or left & right:
        return True
    return ("inventory" in left and bool({"ae_terminal", "bq_screen"} & right)
            or "inventory" in right and bool({"ae_terminal", "bq_screen"} & left))


def conflict(left, right):
    a, _, mod_a = left.partition(":")
    b, _, mod_b = right.partition(":")
    if a == "0" or b == "0":
        return False
    return a == b and (mod_a == mod_b or not (mod_a and mod_b))


def check_layout(bindings):
    base = [binding for binding in bindings if binding.ids[0] in VANILLA]
    if {binding.ids[0] for binding in base} != VANILLA or any(row.default != row.preset for row in base):
        raise ValueError("Preserve the vanilla actions and defaults")
    for binding in bindings:
        code = int(binding.preset.partition(":")[0])
        if binding.ids[0] not in VANILLA and code in RESERVED:
            raise ValueError(f"Reserved Minecraft key used by {binding.ids[0]}")
    conflicts = [(left.ids[0], right.ids[0]) for left, right in combinations(bindings, 2)
                 if overlaps(left.contexts, right.contexts) and conflict(left.preset, right.preset)]
    if conflicts:
        raise ValueError(f"Overlapping bindings: {conflicts}")


VANILLA = frozenset({
    "key.attack", "key.use", "key.pickItem", "key.forward", "key.left", "key.back", "key.right",
    "key.jump", "key.sneak", "key.sprint", "key.drop", "key.inventory", "key.chat", "key.playerlist",
    "key.command", "key.screenshot", "key.togglePerspective", "key.smoothCamera", "key.fullscreen",
    "key.spectatorOutlines", "key.swapHands", "key.saveToolbarActivator", "key.loadToolbarActivator",
    "key.advancements", *(f"key.hotbar.{slot}" for slot in range(1, 10)),
})


def render(bindings):
    lines = ["# Nuclear Tech Reborn (Minecraft 1.12.2 / Forge)", "# Generated by tools/keybinds/build_preset.py"]
    lines.extend(f"key_{name}:{binding.preset}" for binding in bindings for name in binding.ids)
    return ("\n".join(lines) + "\n").encode("utf-8")


if __name__ == "__main__":
    rows = load_bindings()
    check_layout(rows)
    PRESET.write_bytes(render(rows))
